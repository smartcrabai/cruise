//! Best-effort Slack incoming webhook delivery.
#![expect(dead_code, reason = "shared by binary and library notification paths")]

use std::time::{Duration, SystemTime, UNIX_EPOCH};

pub(crate) const WEBHOOK_URL_ENV: &str = "CRUISE_NOTIFY_WEBHOOK";
pub(crate) const WEBHOOK_TIMEOUT: Duration = Duration::from_secs(10);

pub(crate) fn url_from_env() -> Option<String> {
    let value = std::env::var(WEBHOOK_URL_ENV).ok()?;
    let value = value.trim();
    let parsed = url::Url::parse(value).ok()?;
    if matches!(parsed.scheme(), "http" | "https") && parsed.host().is_some() {
        Some(value.to_owned())
    } else {
        None
    }
}

pub(crate) fn slack_text(title: &str, body: &str) -> String {
    format!("{title}: {body}")
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}

pub(crate) fn request_body(text: &str) -> String {
    serde_json::json!({"text": text}).to_string()
}

#[derive(Debug, PartialEq, Eq)]
pub(crate) enum WebhookError {
    Timeout,
    Status(u16),
    Transport,
}

impl std::fmt::Display for WebhookError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Timeout => write!(f, "timeout"),
            Self::Status(code) => write!(f, "http status {code}"),
            Self::Transport => write!(f, "transport error"),
        }
    }
}

pub(crate) fn post(url: &str, body: &str, timeout: Duration) -> Result<(), WebhookError> {
    let agent: ureq::Agent = ureq::Agent::config_builder()
        .timeout_global(Some(timeout))
        .max_redirects(0)
        .http_status_as_error(false)
        .build()
        .into();
    let response = agent
        .post(url)
        .header("Content-Type", "application/json")
        .send(body)
        .map_err(|error| match error {
            ureq::Error::Timeout(_) => WebhookError::Timeout,
            ureq::Error::StatusCode(code) => WebhookError::Status(code),
            _ => WebhookError::Transport,
        })?;
    let status = response.status().as_u16();
    if (200..300).contains(&status) {
        Ok(())
    } else {
        Err(WebhookError::Status(status))
    }
}

pub(crate) fn record_outcome(result: &Result<(), WebhookError>) {
    let Ok(dir) = crate::paths::state_dir() else {
        return;
    };
    let path = dir.join("notification-webhook-error");
    match result {
        Ok(()) => {
            let _ = std::fs::remove_file(path);
        }
        Err(error) => {
            let Ok(now) = SystemTime::now().duration_since(UNIX_EPOCH) else {
                return;
            };
            if std::fs::create_dir_all(dir).is_ok() {
                let _ = std::fs::write(path, format!("{} {error}\n", now.as_secs()));
            }
        }
    }
}

pub(crate) fn last_error() -> Option<(u64, String)> {
    let contents = std::fs::read_to_string(
        crate::paths::state_dir()
            .ok()?
            .join("notification-webhook-error"),
    )
    .ok()?;
    let (timestamp, classification) = contents.trim().split_once(' ')?;
    let timestamp = timestamp.parse().ok()?;
    // Only display classifications generated by this module, never arbitrary file contents.
    if classification != "timeout"
        && classification != "transport error"
        && classification
            .strip_prefix("http status ")
            .is_none_or(|v| v.parse::<u16>().is_err())
    {
        return None;
    }
    Some((timestamp, classification.to_owned()))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::test_support::{EnvGuard, lock_process};
    use std::io::{Read, Write};
    use std::net::TcpListener;

    #[test]
    fn validates_environment_and_encodes_slack_text() {
        let _lock = lock_process();
        for value in ["", "   ", "ftp://x", "not a url"] {
            let _env = EnvGuard::set(WEBHOOK_URL_ENV, value);
            assert_eq!(url_from_env(), None);
        }
        for value in ["https://hooks.example.test/T/S", "http://127.0.0.1:1/x"] {
            let _env = EnvGuard::set(WEBHOOK_URL_ENV, format!("  {value}  "));
            assert_eq!(url_from_env().as_deref(), Some(value));
        }
        assert_eq!(
            slack_text("Cruise", "Failed -- a<b>&c"),
            "Cruise: Failed -- a&lt;b&gt;&amp;c"
        );
        assert_eq!(request_body("x"), r#"{"text":"x"}"#);
    }

    fn server(response: String) -> (String, std::thread::JoinHandle<String>) {
        let listener = TcpListener::bind("127.0.0.1:0")
            .unwrap_or_else(|error| panic!("bind webhook test listener: {error}"));
        let url = format!(
            "http://{}/hook",
            listener
                .local_addr()
                .unwrap_or_else(|error| panic!("get webhook test listener address: {error}"))
        );
        let thread = std::thread::spawn(move || {
            let (mut stream, _) = listener
                .accept()
                .unwrap_or_else(|error| panic!("accept webhook test connection: {error}"));
            stream
                .set_read_timeout(Some(Duration::from_secs(2)))
                .unwrap_or_else(|error| panic!("set webhook test read timeout: {error}"));
            let mut data = Vec::new();
            let mut buffer = [0; 1024];
            loop {
                let count = stream
                    .read(&mut buffer)
                    .unwrap_or_else(|error| panic!("read webhook test request: {error}"));
                if count == 0 {
                    break;
                }
                data.extend_from_slice(&buffer[..count]);
                if let Some(end) = data.windows(4).position(|w| w == b"\r\n\r\n") {
                    let headers = String::from_utf8_lossy(&data[..end]);
                    let length = headers
                        .lines()
                        .find_map(|line| {
                            line.to_ascii_lowercase()
                                .strip_prefix("content-length:")
                                .and_then(|n| n.trim().parse::<usize>().ok())
                        })
                        .unwrap_or(0);
                    if data.len() >= end + 4 + length {
                        break;
                    }
                }
            }
            stream
                .write_all(response.as_bytes())
                .unwrap_or_else(|error| panic!("write webhook test response: {error}"));
            String::from_utf8(data)
                .unwrap_or_else(|error| panic!("decode webhook test request as UTF-8: {error}"))
        });
        (url, thread)
    }

    #[test]
    fn post_sends_json_and_classifies_status_without_redirects() {
        let body = request_body("hello");
        let (url, thread) = server("HTTP/1.1 200 OK\r\nContent-Length: 0\r\n\r\n".into());
        assert_eq!(post(&url, &body, Duration::from_secs(2)), Ok(()));
        let request = thread
            .join()
            .unwrap_or_else(|error| panic!("webhook test server thread failed: {error:?}"));
        assert!(request.starts_with("POST /hook HTTP/1.1\r\n"));
        assert!(
            request
                .to_ascii_lowercase()
                .contains("content-type: application/json\r\n")
        );
        assert!(request.ends_with(&body));
        for code in [500, 302] {
            let (url, thread) = server(format!(
                "HTTP/1.1 {code} Test\r\nLocation: http://127.0.0.1:1/secret\r\nContent-Length: 0\r\n\r\n"
            ));
            assert_eq!(
                post(&url, &body, Duration::from_secs(2)),
                Err(WebhookError::Status(code))
            );
            thread
                .join()
                .unwrap_or_else(|error| panic!("webhook test server thread failed: {error:?}"));
        }
        let listener = TcpListener::bind("127.0.0.1:0")
            .unwrap_or_else(|error| panic!("bind webhook test listener: {error}"));
        let addr = listener
            .local_addr()
            .unwrap_or_else(|error| panic!("get webhook test listener address: {error}"));
        drop(listener);
        assert_eq!(
            post(
                &format!("http://{addr}/services/SECRET123"),
                &body,
                Duration::from_secs(2)
            ),
            Err(WebhookError::Transport)
        );
        for error in [
            WebhookError::Timeout,
            WebhookError::Status(500),
            WebhookError::Transport,
        ] {
            assert!(!error.to_string().contains("SECRET123"));
        }
    }

    #[test]
    fn post_times_out_and_records_sanitized_errors() {
        let listener = TcpListener::bind("127.0.0.1:0")
            .unwrap_or_else(|error| panic!("bind webhook test listener: {error}"));
        let url = format!(
            "http://{}/hook",
            listener
                .local_addr()
                .unwrap_or_else(|error| panic!("get webhook test listener address: {error}"))
        );
        let thread = std::thread::spawn(move || {
            let (_stream, _) = listener
                .accept()
                .unwrap_or_else(|error| panic!("accept webhook test connection: {error}"));
            std::thread::sleep(Duration::from_millis(500));
        });
        assert_eq!(
            post(&url, "{}", Duration::from_millis(100)),
            Err(WebhookError::Timeout)
        );
        thread
            .join()
            .unwrap_or_else(|error| panic!("webhook test server thread failed: {error:?}"));
        let _lock = lock_process();
        let temp = tempfile::tempdir()
            .unwrap_or_else(|error| panic!("create webhook state test directory: {error}"));
        let _env = EnvGuard::set("XDG_STATE_HOME", temp.path());
        record_outcome(&Err(WebhookError::Status(500)));
        let (timestamp, classification) =
            last_error().unwrap_or_else(|| panic!("recorded webhook error is unavailable"));
        assert!(timestamp > 0);
        assert_eq!(classification, "http status 500");
        let path = temp.path().join("cruise/notification-webhook-error");
        assert_eq!(
            std::fs::read_to_string(&path)
                .unwrap_or_else(|error| panic!("read recorded webhook error: {error}")),
            format!("{timestamp} http status 500\n")
        );
        record_outcome(&Ok(()));
        assert!(!path.exists());
        assert_eq!(last_error(), None);
    }
}
