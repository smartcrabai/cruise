#!/usr/bin/env bash
# Run independent checks even after a failure, preserving narrowly scoped reports.
set -uo pipefail
ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
cd "$ROOT" || exit 1
REPORTS="$ROOT/target/formal-reports"
mkdir -p "$REPORTS"
# Each invocation gets a fresh directory so stale receipts cannot mask failures.
RUN=$(mktemp -d "$REPORTS/run.XXXXXX")
status=0
run_check() {
  local name=$1
  shift
  echo "== $name"
  printf '%q ' "$@" >> "$RUN/commands.log"
  printf '\n' >> "$RUN/commands.log"
  "$@" > "$RUN/$name.log" 2>&1
  local result=$?
  cat "$RUN/$name.log"
  printf '%s: %s\n' "$name" "$result" >> "$RUN/results.log"
  if [[ $result != 0 ]]; then status=1; fi
  return 0
}
run_check setup bash scripts/setup_formal.sh
if [[ -f target/formal-tools/env.sh ]]; then
  # shellcheck disable=SC1091 # Generated by setup_formal.sh.
  source target/formal-tools/env.sh
fi
QUINT="$ROOT/tests/formal/node_modules/.bin/quint"
MODEL=tests/formal/checkpoint.qnt
# shellcheck disable=SC2016 # Positional argument is expanded by the child shell.
run_check versions bash -c 'node --version && java -version && "$1" --version && rustc +1.99.1 --version' _ "$QUINT"
run_check alloy-version java -jar target/formal-tools/alloy-6.2.0.jar version
run_check quint-typecheck-help "$QUINT" typecheck --help
run_check quint-test-help "$QUINT" test --help
run_check quint-run-help "$QUINT" run --help
run_check quint-verify-help "$QUINT" verify --help
run_check alloy-exec-help java -jar target/formal-tools/alloy-6.2.0.jar help exec
run_check quint-typecheck "$QUINT" typecheck "$MODEL"
run_check quint-test "$QUINT" test "$MODEL" --main checkpoint --backend typescript --seed 20261023 --out-itf "$RUN/test_{test}_{seq}.itf.json"
run_check quint-simulation "$QUINT" run "$MODEL" --main checkpoint --init init --step step --invariant safety --backend typescript --seed 20261023 --max-samples 100 --max-steps 12 --out-itf "$RUN/simulation_{seq}.itf.json"
# shellcheck disable=SC2329 # Invoked indirectly by run_check.
verify_quint() {
  node - "$QUINT" "$MODEL" "$RUN/counterexample.itf.json" <<'NODE'
const net = require('node:net');
const { spawn } = require('node:child_process');
// Ask the OS for an unused loopback port, not Quint's shared default endpoint.
// Release it immediately before spawning so Quint launches the requested version.
const reservation = net.createServer();
reservation.on('error', error => { console.error(error); process.exitCode = 1; });
reservation.listen(0, '127.0.0.1', () => {
  const port = reservation.address().port;
  reservation.close(() => {
    const endpoint = `127.0.0.1:${port}`;
    console.log(`Isolated Apalache 0.62.1 endpoint: ${endpoint}`);
    const args = [process.argv[2], 'verify', process.argv[3],
      '--main', 'checkpoint', '--init', 'init', '--step', 'step',
      '--invariant', 'safety', '--invariants',
      'cp01_accounting', 'cp02_pending', 'cp03_checkpoint_gate', 'cp04_skip',
      'cp05_resume', 'cp06_reject', 'cp07_group', 'cp08_completed',
      '--max-steps', '12', '--backend', 'apalache', '--apalache-version', '0.62.1',
      '--server-endpoint', endpoint, '--out-itf', process.argv[4]];
    console.log(`Command argv: ${JSON.stringify([process.execPath, ...args])}`);
    const child = spawn(process.execPath, args, { stdio: 'inherit' });
    child.on('error', error => { console.error(error); process.exitCode = 1; });
    child.on('exit', (code, signal) => {
      if (signal) console.error(`Quint terminated by ${signal}`);
      process.exitCode = code ?? 1;
    });
    for (const signal of ['SIGINT', 'SIGTERM']) {
      process.on(signal, () => child.kill('SIGINT'));
    }
  });
});
NODE
}
run_check quint-verify verify_quint
run_check alloy java -jar target/formal-tools/alloy-6.2.0.jar exec --command '*' --type json --output "$RUN/alloy" tests/formal/checkpoint.als
# shellcheck disable=SC2329 # Invoked indirectly by run_check.
alloy_expectations() {
  node - "$ROOT/tests/formal/checkpoint.als" "$RUN/alloy/receipt.json" <<'NODE'
const fs = require('node:fs');
const model = fs.readFileSync(process.argv[2], 'utf8')
  .replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');
const receipt = JSON.parse(fs.readFileSync(process.argv[3], 'utf8'));
const commands = [...model.matchAll(/^\s*(run|check)\s+([A-Za-z_][A-Za-z_0-9]*)\b/gm)];
if (!commands.length) throw Error('No named Alloy commands found');
const seen = new Set();
for (let i = 0; i < commands.length; i++) {
  const match = commands[i];
  const name = match[2];
  const text = model.slice(match.index, commands[i + 1]?.index ?? model.length);
  const expected = text.match(/\bexpect\s+([01])\b/);
  if (!expected) throw Error(`Alloy command ${name} needs explicit expect 0 or 1`);
  if (seen.has(name)) throw Error(`Duplicate Alloy command ${name}`);
  seen.add(name);
  const actual = receipt.commands?.[name];
  if (!actual || actual.type !== match[1]) throw Error(`Missing Alloy result: ${name}`);
  const sat = Array.isArray(actual.solution) && actual.solution.length > 0;
  if (Number(sat) !== Number(expected[1])) throw Error(`Alloy ${name}: expected ${expected[1]}, got ${Number(sat)}`);
  if ((actual.expects ?? 0) !== Number(expected[1])) throw Error(`Receipt expectation differs: ${name}`);
  console.log(`${name}: ${sat ? 'SAT' : 'UNSAT'}, expect ${expected[1]} passed`);
}
if (Object.keys(receipt.commands).length !== seen.size) throw Error('Alloy command coverage mismatch');
NODE
}
run_check alloy-expectations alloy_expectations
run_check checkpoint-bdd cargo +1.99.1 test --locked --test graph_state --test checkpoint_bdd
printf 'Aggregate exit status: %s\n' "$status" | tee -a "$RUN/results.log"
echo "Reports: $RUN"
exit "$status"
